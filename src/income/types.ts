// A "Job" is money in — what a sole trader actually thinks about (a job for Mike,
// £800), not an abstract "income entry". One Job is one piece of work billed to a
// client, paid or not yet paid. Mirrors the Receipt shape so the income layer can
// reuse the same MMKV-first + self-healing Supabase sync pattern.

import type { HMRCCategory } from '../receipts/types';

// 'quoted' is the pre-income lifecycle stage: an estimate the trader has issued
// but the customer hasn't accepted. A quoted job is NEVER turnover — it's excluded
// from every income / profit / tax figure (the income gate) until it's converted
// to an invoice, at which point it becomes 'unpaid' (→ 'paid' when the money
// arrives). 'void' is a cancelled job.
export type JobStatus = 'quoted' | 'unpaid' | 'paid' | 'void';

// How the job entered the app. 'manual' = typed in via the Jobs + (no document).
// 'camera' / 'share' = a document (invoice) routed through the AI pipeline — those
// land as needs_review. 'invoice' = generated by SoleTax's own invoice builder
// (the PDF is the job's document, stored as imageUri/imagePath).
export type JobSource = 'manual' | 'camera' | 'share' | 'invoice';

// One line on a generated invoice — what the trader is billing for and the
// price they're charging (the selling price; linked-receipt costs never appear
// here, Session 29). Amount in pence, always GBP.
export interface LineItem {
  description: string;
  amount: number; // pence
}

// One generated customer document kept against the job — a quote or the invoice
// it became. A job accumulates these (full history): the quote is preserved when
// it converts to an invoice, so the trader keeps the whole paper trail (what was
// quoted vs invoiced). One entry per distinct document (keyed by kind+number);
// re-saving the same document updates its entry in place rather than stacking.
// The newest entry is the job's "active" document (shown in the hub's top pane);
// the rest live in the Documents list. Backed up like job photos — the PDF goes to
// the `income` Storage bucket (path), downloaded lazily on view via resolveDocument.
export interface JobDocument {
  id: string;            // stable id, also the Storage filename stem
  kind: 'quote' | 'invoice';
  number?: string;       // QUO-001 / INV-001 at generation
  amount: number;        // pence — the document total
  date: string;          // ISO YYYY-MM-DD — the document date
  createdAt: number;     // Unix ms generated — sort key (newest first = active)
  uri?: string;          // local path to the generated PDF
  path?: string;         // Supabase Storage path (restore)
  // ── Snapshot of the builder fields that produced this document ────────────────
  // Captured at save so tapping the document reopens the builder showing EXACTLY
  // what generated it, and so deleting the active document and reverting to an older
  // one restores the right line items (not the latest). Absent on documents made
  // before this was added (legacy) — the builder then falls back to the job's
  // current fields. amount/date/number/kind above are the headline; these are the
  // rest of the editable form. Stored in the `documents` jsonb (additive — no
  // migration) and restored via the spread in cloudRestore.
  lineItems?: LineItem[];
  client?: string;
  clientAddress?: string;
  jobDescription?: string;
  dueDate?: string;       // due date (invoice) / valid-until (quote)
  supplyDate?: string;    // work completed (invoice only)
}

// One spoken note kept against the job. A job accumulates these (full history) the
// same way it accumulates documents — newest first, each dated, individually
// deletable. The FIRST is captured through the invoice builder ("Talk through the
// job", which also builds the quote); further ones are added straight to the job
// ("Add voice note"). Whenever a recording is added its transcript is also appended
// to the job's running `notes` log (the source of truth — see Job.notes), so the
// words survive even if the audio is later deleted. Backed up like a document: the
// audio file goes to the `income` Storage bucket (path), re-downloaded lazily on
// play via resolveRecordingOrCloud.
export interface VoiceNote {
  id: string;            // stable id, also the Storage filename stem
  createdAt: number;     // Unix ms recorded — sort key (newest first)
  date: string;          // ISO YYYY-MM-DD — the row's date label
  transcript: string;    // this recording's own speech-to-text
  waveform?: number[];   // 0..1 amplitude bars for the playback waveform
  uri?: string;          // local path to the recording (.wav/.m4a)
  path?: string;         // Supabase Storage path (restore)
}

export interface Job {
  id: string;
  // Local-only, never uploaded — the auth uid this record was created/restored
  // under (S142 uid guard; see Receipt.ownerUid).
  ownerUid?: string;
  createdAt: number;                 // Unix ms when logged
  client?: string;                   // optional — a cash job may have no named client
  amount: number;                    // in pence, always GBP
  date: string;                      // ISO YYYY-MM-DD — the job / invoice date
  invoiceNumber?: string;            // set by invoice generation; absent for manual cash jobs
  // Set when the job was issued as a quote (its own QUO- sequence — a quote never
  // burns an invoice number). Kept for provenance after a quote→invoice convert.
  // Synced (20260619), like supplyDate below.
  quoteNumber?: string;
  status: JobStatus;                 // quoted → unpaid (on convert) → paid when the money arrives
  paidAt?: number;                   // Unix ms when marked paid
  // CIS deduction the contractor withheld from this payment (register §I —
  // labour only, never materials/VAT; the figure is on the contractor's monthly
  // statement). Pence. Shown on paid jobs when Tax setup says the user works
  // under CIS; nets the tax estimate (engine cisDeductionsWithheld). Synced
  // (20260619) so a restored CIS user's tax estimate stays correct.
  cisWithheld?: number;
  // The job's running, dated note log — the single source of truth for everything
  // written about the job. The user types into it freely (one editor over the whole
  // string), and every voice note appends its transcript under a `12 Jun 2026`
  // heading (see store.addVoiceNote). A plain string so the editor stays trivial;
  // the dated structure is just text with headings the hub styles on render.
  notes?: string;
  source: JobSource;
  // Invoice-builder jobs (source 'invoice') carry the billed line items, the
  // client's address (for the invoice header) and a due date. amount stays = the
  // sum of lineItems. The generated PDF is stored as the job's document below.
  lineItems?: LineItem[];
  clientAddress?: string;
  dueDate?: string;                  // ISO YYYY-MM-DD — payment due (invoice) or "valid until" (quote)
  // "Still owed" acknowledgement (Home "To sort"): tapping it on an overdue job
  // snoozes it OUT of the To-sort inbox for a week so a slow payer can't nag daily;
  // the job stays in the Jobs hub Overdue section throughout. SYNCED since
  // 2026-09-05 (ruling — was local-only): the portal runs the SAME isJobInToSort
  // predicate, so an unsynced ack meant the desk nagged about a job the phone was
  // already told to quiet. Never a tax figure, never a searchable record
  // (20260905_due_ack_sync.sql). See src/income/dueStatus.isJobInToSort.
  dueAckAt?: number;                 // Unix ms the user last acked it as still owed
  // Invoice fields, synced (20260619): the supply date ("Work completed", legally
  // required — register §A; defaults to the job date) and the job description line
  // shown in the invoice's job panel.
  supplyDate?: string;               // ISO YYYY-MM-DD
  jobDescription?: string;
  // The job's voice notes (recordings), newest first. Each is dated, plays its own
  // transcript, and is individually deletable. Backed up to the `income` bucket
  // (one object per note, id-keyed) + the `voice_notes` jsonb column; restored
  // lazily on play. Mirrors `documents` above.
  voiceNotes?: VoiceNote[];
  // ── LEGACY single voice note (pre-multi) — DO NOT write going forward. ──────────
  // Kept on the type only so the one-time local migration (store onRehydrate) and a
  // restore of an old row can fold them into voiceNotes[]. Once migrated these are
  // cleared. Nothing should read these for display.
  audioUri?: string;                 // legacy: local path to the recording
  audioPath?: string;                // legacy: Supabase Storage path
  transcript?: string;               // legacy: speech-to-text of the dictation
  waveform?: number[];               // legacy: amplitude bars
  // Private job photos (finished work, site shots) the trader keeps as a record —
  // shown in the job hub's Summary, never on the customer invoice/quote (locked
  // design note). Backed up to the `income` Storage bucket; `photoPaths` holds the
  // Storage paths parallel to `photoUris` so a new device recovers them (the files
  // are downloaded lazily on view via resolveDocument, like a receipt image).
  photoUris?: string[];              // local paths to persisted job photos
  photoPaths?: string[];             // Supabase Storage paths, parallel to photoUris (restore)
  // The job's customer documents (quotes + invoices), newest first. The newest is
  // the "active" doc and its uri/path are mirrored onto imageUri/imagePath below so
  // the hub's top pane, sharing and existing restore keep working unchanged. Absent
  // on manual/AI-captured jobs (those carry a single imageUri, no document list).
  documents?: JobDocument[];
  imageUri?: string;                 // present for document-sourced jobs (invoice photo/PDF/generated)
  imagePath?: string;                // Supabase Storage path once synced
  taxYear: string;                   // e.g. "2025-26"
  // Manual entries are the review (the user typed them) → 'approved' on save.
  // Document-sourced jobs land 'needs_review' until confirmed.
  reviewStatus: 'needs_review' | 'approved';
  syncStatus: 'local' | 'uploading' | 'synced' | 'upload_failed';
  syncedAt?: number;                 // Unix ms when the backup last succeeded — drives the "Backed up" flash
  // Last content edit, ms, any client — the sync spine's LWW authority (see
  // Receipt.updatedAtMs). Absent on pre-spine records → rank at createdAt.
  updatedAtMs?: number;
  // One-step undo snapshot (MMKV-only, never synced): the *other* version of the
  // user-editable fields after an AI/auto overwrite, powering the persistent
  // Revert ⇄ Redo toggle. `mine` = true when `values` is what the user typed.
  revertSnapshot?: { values: JobValues; mine: boolean };
}

// The user-editable fields that an AI/auto overwrite can replace — snapshotted for
// the Revert ⇄ Redo toggle.
export interface JobValues {
  amount: number;
  client?: string;
  date: string;
  notes?: string;
}

// ── Other income (non-invoiced business income) ──────────────────────────────
// A Job is invoiced/client work. But turnover is NOT only jobs: a sole trader
// also has money in that never went through an invoice — cash takings, tips,
// product/market sales — plus genuine "other business income" (letting part of
// the premises, a VAT repayment) and the proceeds of selling a business asset.
// Without a home for these, the app's "income = jobs" mental model causes the
// real failure mode: OMISSION → an under-reported return. OtherIncome is that
// home. Each carries a `kind` that the income source-of-truth (incomeBoxes-2026)
// routes to its SA103F box (15 vs 16) and decides whether it needs review.
//
// It is deliberately lightweight — amount, date, note — no invoice/client/quote
// scaffolding (that's what a Job is for). It still counts as turnover exactly
// like a paid job: selectEstimateInputs + mtdPack sum it into incomeReceived /
// turnover. Mirrors the Job sync/review shape so it reuses the same MMKV-first +
// self-healing Supabase backup pattern (it is income — never lose it on-device).
export type OtherIncomeKind =
  // ── Box 15 (turnover) ──
  | 'cash_takings'   // cash/card sales with no invoice; market/product/stall sales
  | 'sales'          // sales income imported from previous software (the switcher
                     // importer, docs/specs/switcher_importer.md) — item-level
                     // turnover rows; plain Box 15, hidden from the manual picker
  | 'tips'           // tips, gratuities, service charge kept by the trader
  | 'asset_sale'     // proceeds of selling a tool/van/equipment the business
                     // expensed (under cash basis a disposal is a taxable receipt
                     // — HS222 §11; NOT a capital-allowances balancing charge)
  // ── Box 16 (other business income) ──
  | 'letting'        // letting part of your business premises / right to cross land
  | 'vat_repayment'  // a net VAT repayment received from HMRC (figures incl. VAT).
                     // RETIRED from the manual picker 2026-08-04 (the external accountant reviewer's
                     // review) — legacy rows only; see incomeBoxes-2026
  | 'refund'         // money BACK on a business cost — a supplier refund or rebate.
                     // A trade RECEIPT under cash basis (BIM72015/72020 + the
                     // SA103F Box-16 VAT-repayment precedent; register §F,
                     // ruling 2026-07-10) — never a negative expense: amounts
                     // stay positive, Box 15 turnover stays untouched
  // ── Box 16, but always flag for review (grey area — never auto-route) ──
  | 'other'          // anything else, incl. grants — routed to review, not guessed
  // ── Box 60 — goods/stock taken for own use (an ADD-BACK, not money received) ──
  | 'goods_own_use'; // captured via the same Other sheet, but it is NOT income
                     // received: the cost is ADDED BACK to taxable profit (SA103F
                     // Box 60). Excluded from the "received" displays + records
                     // search; folded into the estimate + tagged Box 60 on export.

export interface OtherIncome {
  id: string;
  createdAt: number;                 // Unix ms when logged
  amount: number;                    // in pence, always GBP — the amount RECEIVED
  date: string;                      // ISO YYYY-MM-DD — when the money came in (cash basis)
  kind: OtherIncomeKind;             // routed to its SA103F box by incomeBoxes-2026
  // Local-only, never uploaded — the auth uid this record was created/restored
  // under (S142 uid guard; see Receipt.ownerUid).
  ownerUid?: string;
  note?: string;                     // free text — what it was
  // How the row entered the app. Absent = typed by hand (the pre-importer
  // default). 'import' = the switcher importer (docs/specs/switcher_importer.md).
  source?: 'manual' | 'import';
  // The import batch this row arrived in — one tap reverts the whole batch
  // (the always-revert rule). Absent on non-imported rows.
  importBatchId?: string;
  // 'refund' rows only: the expense category this refund relates to (from the
  // import's mapping or the converted receipt). Filing never needs it (Box 16
  // stands alone) — it preserves the information so a future per-category net
  // view CAN exist (ruling 2026-07-10: decision deferred, data not lost).
  // Local-only for now; joins the sync schema if that view ever ships.
  refundCategory?: HMRCCategory;
  taxYear: string;                   // e.g. "2025-26" (derived from `date`)
  // Manual entries are the review (the user typed them) → 'approved' on save.
  // A grey-area kind ('other') lands 'needs_review' until confirmed, like a
  // document-sourced job.
  reviewStatus: 'needs_review' | 'approved';
  // Why this record was flagged needs_review (ImportRowFlag values, plain
  // strings). SYNCED since 2026-07-13 (ruling — was local-only): see
  // Receipt.reviewReasons (S143).
  reviewReasons?: string[];
  syncStatus: 'local' | 'uploading' | 'synced' | 'upload_failed';
  syncedAt?: number;                 // Unix ms when the backup last succeeded
  // Last content edit, ms, any client — the sync spine's LWW authority (see
  // Receipt.updatedAtMs). Absent on pre-spine records → rank at createdAt.
  updatedAtMs?: number;
}
